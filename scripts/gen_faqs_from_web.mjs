import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..');
const src = path.join(
  root,
  'firststep_frontend/src/firstStepComponents/firstStepMarketing/FAQPage.tsx',
);
const dest = path.join(
  root,
  'firststep_mobile/lib/features/profile/content/landing_faqs.dart',
);

const s = fs.readFileSync(src, 'utf8');
const start = s.indexOf('const faqs: FAQ[] = [');
const end = s.indexOf('];', start);
const block = s.slice(start, end + 2);
const items = [];
const re =
  /\{\s*id:\s*(\d+),\s*question:\s*'((?:\\'|[^'])*)',\s*answer:\s*'((?:\\'|[^'])*)',\s*category:\s*'((?:\\'|[^'])*)',\s*tags:/gs;
let m;
while ((m = re.exec(block))) {
  const unescape = (t) => t.replace(/\\'/g, "'").replace(/\\n/g, '\n');
  items.push({
    id: Number(m[1]),
    q: unescape(m[2]),
    a: unescape(m[3]),
    c: unescape(m[4]),
  });
}

const esc = (t) =>
  t
    .replace(/\\/g, '\\\\')
    .replace(/\$/g, () => '\\$')
    .replace(/'/g, "\\'");
const categories = [
  'All',
  'About FirstStep',
  'Getting Started',
  'Plans, Pricing & Refund',
  'Resume & Applications Support',
  'Dashboard & Tracking',
  'Payments & Billing',
  'Learning Center & Interview Prep',
  'Account Management',
  'Privacy & Data Security',
  'Technical & Support Help',
];

let out = `// FAQ content mirrored from web FAQPage (firststep_frontend).
// Generated by scripts/gen_faqs_from_web.mjs — re-run after FAQPage.tsx changes.

class LandingFaq {
  const LandingFaq({
    required this.id,
    required this.question,
    required this.answer,
    required this.category,
  });

  final int id;
  final String question;
  final String answer;
  final String category;
}

const faqCategories = <String>[
${categories.map((c) => `  '${esc(c)}',`).join('\n')}
];

const landingFaqs = <LandingFaq>[
`;

for (const it of items) {
  out += `  LandingFaq(
    id: ${it.id},
    category: '${esc(it.c)}',
    question: '${esc(it.q)}',
    answer:
        '${esc(it.a)}',
  ),
`;
}
out += '];\n';

fs.writeFileSync(dest, out);
console.log(`Wrote ${items.length} FAQs to ${dest}`);
